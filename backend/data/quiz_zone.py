# Helper functions to get questions
def get_bahasa_indonesia_questions(level: int) -> list:
    """Get Bahasa Indonesia multiple choice questions for a specific level"""
    level_key = f"level_{level}"
    return BAHASA_INDONESIA_MCQ.get(level_key, [])

def get_english_questions(level: int) -> list:
    """Get English multiple choice questions for a specific level"""
    level_key = f"level_{level}"
    return ENGLISH_MCQ.get(level_key, [])

def get_matematika_questions(level: int) -> list:
    """Get Matematika multiple choice questions for a specific level"""
    level_key = f"level_{level}"
    return MATEMATIKA_MCQ.get(level_key, [])

def get_questions_by_category(category: str, level: int) -> list:
    """Get questions by category and level"""
    category_map = {
        "indonesia": get_bahasa_indonesia_questions,
        "bahasa_indonesia": get_bahasa_indonesia_questions,
        "english": get_english_questions,
        "matematika": get_matematika_questions,
        "math": get_matematika_questions,
    }
    
    getter = category_map.get(category.lower(), get_bahasa_indonesia_questions)
    return getter(level)
